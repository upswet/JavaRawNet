package rawnet.code.rl;

/**
 * Среда, в которой действует RL-агент.
 *
 * <h2>Что это</h2>
 * Среда — это «мир», с которым взаимодействует агент. Она умеет:
 * <ul>
 *   <li>начать новый эпизод — {@link #reset()};</li>
 *   <li>сделать шаг по действию агента — {@link #step(int)}.</li>
 * </ul>
 * Больше ничего. Среда <b>не знает</b>, какой алгоритм её использует
 * (REINFORCE, DQN, PPO, …) — она просто принимает действие и
 * возвращает новое наблюдение, награду и флаг «эпизод закончен».
 *
 * <h2>Эпизод</h2>
 * Работа со средой всегда идёт <b>эпизодами</b>:
 * <pre>{@code
 * float[] s = env.reset();              // начало эпизода
 * while (true) {
 *     int a = policy.chooseAction(s);   // агент выбирает действие
 *     StepResult r = env.step(a);       // среда делает шаг
 *     s = r.observation();              // новое наблюдение
 *     if (r.done()) break;              // эпизод закончен
 * }
 * }</pre>
 * После {@code done == true} следующий вызов {@link #reset()} начинает
 * <b>новый</b> эпизод. Старое состояние среды после {@code done} не
 * используется.
 *
 * <h2>Примеры сред</h2>
 * <ul>
 *   <li><b>CartPole</b> — тележка с шестом. Наблюдение — 4 числа
 *       {@code [x, x', θ, θ']}, действий — 2 (влево/вправо).</li>
 *   <li><b>cart_pole</b> — сетка, агент ищет цель. Наблюдение —
 *       позиции агента/цели, действий — 4 (вверх/вниз/влево/вправо).</li>
 *   <li><b>TicTacToe</b> — доска 3×3. Наблюдение — 9 чисел (клетки),
 *       действий — 9 (индекс клетки).</li>
 * </ul>
 *
 * <h2>Почему действия — {@code int}, а не {@code float[]}</h2>
 * Для <b>дискретного</b> RL действие — это выбор из {@code numActions}
 * вариантов. Политика выдаёт вероятности (через {@code softmax}),
 * и агент <b>сэмплирует</b> индекс. Это стандарт для CartPole, Atari,
 * cart_pole, TicTacToe. Для <b>непрерывных</b> действий (роботы,
 * управление) понадобится отдельный интерфейс — но в учебных примерах
 * он не нужен.
 *
 * <h2>Почему наблюдение — {@code float[]}</h2>
 * Плоский {@code float[]} — это <b>ровно</b> то, что принимает
 * {@code Functional} на вход. Никаких преобразований: среда возвращает
 * вектор, агент сразу подаёт его в сеть. Для визуальных сред (Atari)
 * это будет развёрнутое изображение; для CartPole — 4 числа.
 */
public interface Environment {

    /**
     * Начать новый эпизод и вернуть начальное наблюдение.
     *
     * <p>Вызывается <b>один раз</b> в начале эпизода, и <b>ещё раз</b>
     * после {@code done == true} (для следующего эпизода). Внутри
     * среда сбрасывает своё состояние в начальное (случайное или
     * фиксированное — зависит от среды).
     *
     * @return начальное наблюдение — то, что агент «видит» в начале
     *         эпизода. Размер — {@link #observationSize()}.
     */
    float[] reset();

    /**
     * Сделать шаг: применить действие {@code action} и вернуть
     * результат.
     *
     * <p>Среда обновляет своё внутреннее состояние (физика, доска,
     * сетка) и возвращает:
     * <ul>
     *   <li><b>новое наблюдение</b> — что агент видит <b>после</b>
     *       действия;</li>
     *   <li><b>награду</b> — насколько хорошо было действие
     *       (для CartPole — {@code +1} за каждый шаг, для TicTacToe —
     *       {@code +1} за победу, {@code -1} за поражение);</li>
     *   <li><b>{@code done}</b> — закончился ли эпизод (шест упал,
     *       доска заполнена, агент дошёл до цели).</li>
     * </ul>
     *
     * <p><b>После</b> {@code done == true} <b>нельзя</b> вызывать
     * {@code step} снова — сначала {@link #reset()}.
     *
     * @param action индекс действия в {@code [0, numActions())}.
     *               Что значит каждое действие — знает <b>среда</b>
     *               (для CartPole: 0 — влево, 1 — вправо).
     * @return результат шага: новое наблюдение, награда, флаг done
     * @throws IllegalArgumentException если {@code action} вне
     *                                  {@code [0, numActions())}
     */
    StepResult step(int action);

    /**
     * Сколько всего действий доступно агенту.
     *
     * <p>Нужно, чтобы создать выход политики: {@code Dense(numActions)}.
     * Для CartPole — 2, для cart_pole — 4, для TicTacToe — 9.
     *
     * @return число дискретных действий; {@code >= 1}
     */
    int numActions();

    /**
     * Размер вектора наблюдения.
     *
     * <p>Нужно, чтобы создать вход политики: {@code InputDto(observationSize)}.
     * Для CartPole — 4, для cart_pole — 2×N², для TicTacToe — 9.
     *
     * @return длина {@code float[]}, который возвращает
     *         {@link #reset()} и {@link #step(int)}
     */
    int observationSize();

    /**
     * Результат одного шага среды.
     *
     * <p>Это <b>record</b> — неизменяемый объект с тремя полями.
     * Среда создаёт новый {@code StepResult} на каждый шаг; агент
     * читает поля и не модифицирует их.
     *
     * @param observation новое наблюдение (что агент видит после
     *                    действия). Размер — {@link #observationSize()}.
     * @param reward      награда за действие (может быть 0, +1, −1,
     *                    дробной — зависит от среды)
     * @param done        {@code true}, если эпизод закончился
     *                    (шест упал, доска заполнена, …)
     */
    record StepResult(float[] observation, float reward, boolean done) {}

    /**
     * Для отладки: напечатать состояние среды в консоль.
     *
     * <p>По умолчанию — ничего. Конкретные среды могут переопределить:
     * CartPole — рисовать тележку и шест, TicTacToe — доску 3×3,
     * cart_pole — сетку. Используется в {@code demoEpisode} после
     * обучения, чтобы <b>видеть</b>, как агент играет.
     */
    default void render() {}
}