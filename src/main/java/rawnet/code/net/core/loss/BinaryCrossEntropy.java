package rawnet.code.net.core.loss;

/**BCE математически предполагает, что каждый элемент target — это вероятность Бернулли, т.е. 0 или 1
 *
 * Бинарная кросс-энтропия для многомерного выхода (многометочная классификация).
 * loss = - Σ [target_i * log(pred_i) + (1 - target_i) * log(1 - pred_i)].
 * Предполагается, что каждый выход независимо проходит через сигмоиду.
 *
 * Сильные стороны: корректная вероятностная интерпретация, быстрый градиент при использовании
 * с сигмоидой (dL/dz = pred - target) при условии объединённой производной.
 *
 * Слабые стороны: если считать производную по pred как (pred - target) / (pred * (1 - pred)),
 * возможна численная нестабильность около 0 и 1. В данной реализации используется именно эта формула,
 * которая корректна только в комбинации с последующей производной сигмоиды в Dense слое,
 * что в итоге даёт градиент pred - target. Следует избегать вызова derivative в отрыве от слоя сигмоиды.
 *
 * <b>Рекомендуемое сочетание:выходной слой строго с Sigmoid-ой.
 */

/*
Логарифм — это операция, обратная возведению в степень. Отвечает на вопрос: «в какую степень нужно возвести основание, чтобы получить данное число?»

log_b(x) = y   ⟺   b^y = x
Читается: «логарифм x по основанию b — это степень y, в которую надо возвести b, чтобы получить x».

log_2(8)   = 3   потому что 2³ = 8
log_10(100) = 2  потому что 10² = 100
log_2(1024) = 10 потому что 2¹⁰ = 1024
log_2(1)    = 0  потому что 2⁰ = 1
log_2(0.5)  = −1 потому что 2⁻¹ = 0.5

Логарифм превращает умножение в сложение, а возведение в степень — в умножение:
log(a · b) = log(a) + log(b)
log(a / b) = log(a) − log(b)
log(a^c)   = c · log(a)
log(1/a)   = −log(a)

Это главное свойство, из-за которого логарифм везде в машинном обучении. Где в формулах есть произведение (вероятностей, шансов, отношений) — логарифм делает из него сумму, с которой проще работать численно и дифференцировать.


Бинарная кросс-энтропия для одного примера с меткой y ∈ {0, 1} и предсказанной вероятностью p = σ(score):
BCE(p, y) = −[ y · log(p) + (1 − y) · log(1 − p) ]
    y = 1 (positive): BCE = −[1·log(p) + 0·log(1−p)] = −log(p). Модель хочет p → 1, тогда −log(p) → 0.
    y = 0 (negative): BCE = −[0·log(p) + 1·log(1−p)] = −log(1−p). Модель хочет p → 0, тогда −log(1−p) → 0.

Подставляя p = σ(s),
    y = 1 → −log σ(s)
    y = 0 → −log(1 − σ(s))


Исходя из
    log(1/x) = −log(x)

    log(a^{-1}) = −log(a)

    log(a·b) = log(a) + log(b)

    1 − σ(s) = 1 − 1/(1+e^{−s}) = e^{−s}/(1+e^{−s}) = 1/(1+e^{s}) = σ(−s)


Следует
    log(1 − σ(s)) = log σ(−s) = −log(1 + e^{s})
 */

public class BinaryCrossEntropy  implements Loss {
    private static final float EPS = 1e-15f;

    public float loss(float[] p, float[] t) {
        float s = 0;
        for (int i = 0; i < p.length; i++)
            s -= t[i] * Math.log(Math.max(p[i], EPS)) + (1 - t[i]) * Math.log(Math.max(1 - p[i], EPS));
        return s / p.length; // усреднение по размерности
    }

    /**
     * Производная бинарной кросс-энтропии по вероятности pred.
     * В паре с Sigmoid (derivative = out*(1-out)) полный градиент по z будет (pred - target).
     */
    public void derivative(float[] p, float[] t, float[] d) {
        for (int i = 0; i < p.length; i++) {
            d[i] = (p[i] - t[i]) / Math.max(p[i] * (1 - p[i]), EPS);
        }
    }
}
