package rawnet.code.net.core;

import java.io.DataInputStream;
import java.io.DataOutputStream;
import java.io.IOException;

/**
 * Объект, умеющий сохранять и восстанавливать своё состояние в бинарный поток.
 *
 * <p>Контракт намеренно минимальный и симметричный:
 * <ul>
 *   <li>{@link #save(DataOutputStream)} пишет <b>всё</b>, что нужно для
 *       восстановления: гиперпараметры, состояние, привязку к массивам —
 *       но <b>не</b> имя класса (имя пишет вызывающий, см. ниже);</li>
 *   <li>{@link #load(DataInputStream)} читает ровно то, что записал
 *       {@code save}, в <b>уже созданный</b> экземпляр.</li>
 * </ul>
 *
 * <h3>Кто пишет имя класса</h3>
 * Имя класса ({@link Class#getName()}) <b>не входит</b> в контракт. Его
 * пишет вызывающий код — тот, кто знает, что перед ним полиморфный объект
 * и как его потом создать (фабрика через рефлексию):
 * <ul>
 *   <li>{@code Layer.save}/{@code Layer.load} — {@code super.save} пишет
 *       {@code UTF className}, наследник дописывает состояние;</li>
 *   <li>{@code TrainingCheckpoint.save/load} для {@link Optimizer} — пишет
 *       {@code UTF className}, затем {@code optimizer.save(out)};</li>
 *   <li>аналогично для {@code Loss}, {@code Activate}, {@code Model}.</li>
 * </ul>
 * Такой контракт позволяет <b>одной</b> утилите полиморфно
 * сохранять/восстанавливать любой {@code Persistable} по имени класса
 * (см. {@code Persistables.save/load}). Он же — точка расширения: новый
 * класс достаточно унаследовать от {@code Persistable} (и, если он
 * полиморфный, дать конструктор без аргументов), чтобы он заработал в
 * общем механизме.
 *
 * <h3>Состояние и привязка к массивам</h3>
 * Если у объекта есть состояние, привязанное к чужим массивам
 * (например, {@code m/v} у {@code AdamW} привязаны к массивам весов
 * слоёв), {@code save} пишет его в порядке, который {@code load} сможет
 * воспроизвести. {@code load} кладёт такое состояние в «отложенные»
 * буферы и привязывает к массивам при первом реальном обращении
 * (например, в {@code updateWeights}/{@code updateBiases}). Так
 * {@code load} не требует, чтобы массивы уже были известны в момент
 * вызова.
 *
 * <h3>Совместимость с {@link java.io.Serializable}</h3>
 * Контракт <b>не наследует</b> {@code Serializable}: это два разных
 * подхода. {@code Serializable} — автоматическая сериализация всей
 * объектной графы (хрупкая к версиям), {@code Persistable} — ручной
 * контроль формата. Классы, реализующие оба, должны позаботиться о
 * согласованности ({@code transient} на несериализуемых полях).
 */
public interface Persistable {

    /**
     * Записать состояние в поток.
     *
     * <p>Не пишет имя класса — его пишет вызывающий.
     *
     * @param out поток для записи; не закрывается методом
     * @throws IOException при ошибке записи
     */
    default void save(DataOutputStream out) throws IOException{};

    /**
     * Прочитать состояние из потока в <b>этот</b> экземпляр.
     *
     * <p>Ожидает ровно тот формат, который записал
     * {@link #save(DataOutputStream)}. Экземпляр должен быть уже создан
     * (обычно — конструктором без аргументов или фабрикой по имени класса).
     *
     * @param in поток для чтения
     * @throws IOException при ошибке чтения или несовместимом формате
     */
    default void load(DataInputStream in) throws IOException{};
}